const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const data=JSON.parse(process.env.UNIFIED_INPUT);
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 try{
  const context=await browser.newContext({viewport:{width:390,height:800},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  await context.addCookies([{name:data.cookie,value:data.token,url:data.base}]);
  const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(data.base+data.catalog);
  await page.locator('[data-bch-consent-banner] [data-bch-consent-reject]').click();
  await page.locator('[data-add]').click();
  const form=page.locator('[data-form]');
  await form.locator('[name=name]').fill('Browser software');
  await form.locator('[name=price]').fill('0.01');
  await form.locator('[name=account]').selectOption(data.account);
  await form.locator('[name=media]').setInputFiles(data.image);
  await form.locator('[name=media]').setInputFiles(data.clip);
  await page.waitForFunction(()=>!document.querySelector('[data-save]').disabled);
  assert.match(await page.locator('[data-media-status]').textContent(),/Video optimized/);
  await form.locator('[name=archive]').setInputFiles({name:'tool.zip',mimeType:'application/zip',buffer:Buffer.from(data.archive,'base64')});
  await form.locator('[name=requirements]').fill('Python 3.13');
  await form.locator('[name=license_text]').fill('Personal use. Source included.');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  fs.mkdirSync('/tmp/bch-unified-software',{recursive:true});
  await page.screenshot({path:'/tmp/bch-unified-software/catalog-mobile.png'});
  await form.locator('[data-save]').click();
  await page.locator('[data-drawer]').waitFor({state:'hidden'});
  await page.locator('[data-rows]').getByText('Browser software',{exact:true}).waitFor();
  await page.goto(data.base+data.store);
  const card=page.locator('[data-software-card]').filter({hasText:'Browser software'});
  await card.scrollIntoViewIfNeeded();
  const video=card.locator('video');
  assert.equal(await video.getAttribute('src'),null,'Reduced motion must avoid video fetch');
  await card.locator('[data-preview-toggle]').click();
  await page.waitForFunction(()=>{const v=document.querySelector('[data-preview-video]');return v.readyState>=2&&!v.paused;});
  assert.equal(await video.evaluate(v=>v.muted&&v.loop&&v.playsInline),true);
  assert.equal(await video.evaluate(v=>getComputedStyle(v).objectFit),'cover');
  assert.equal(await video.evaluate(v=>Math.abs(v.getBoundingClientRect().width-v.parentElement.getBoundingClientRect().width)<1),true);
  await card.locator('[data-preview-toggle]').click();
  assert.equal(await video.evaluate(v=>v.paused),true);
  await page.screenshot({path:'/tmp/bch-unified-software/preview-mobile.png'});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.reload();
  await card.scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>!document.querySelector('[data-preview-video]').paused);
  await page.locator('#software-title').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('[data-preview-video]').paused);
  // Editing metadata must not demand a new ZIP or change the published release.
  await page.goto(data.base+data.catalog);
  await page.locator('[data-op=edit]').click();
  assert.equal(await form.locator('[name=archive]').isVisible(),true);
  await form.locator('[name=description]').fill('Updated description');
  await form.locator('[data-save]').click();
  await page.locator('[data-drawer]').waitFor({state:'hidden'});
  await page.locator('[data-op=edit]').click();
  await form.locator('[name=archive]').setInputFiles({name:'tool-v2.zip',mimeType:'application/zip',buffer:Buffer.from(data.archive,'base64')});
  await form.locator('[name=version]').fill('2.0.0');
  await form.locator('[name=account]').selectOption(data.account);
  await form.locator('[name=requirements]').fill('Python 3.13');
  await form.locator('[name=license_text]').fill('Personal use, version 2.');
  await form.locator('[data-save]').click();
  await page.locator('[data-drawer]').waitFor({state:'hidden'});
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('Unified software passed: mobile create with ZIP/image/video, manual playback under reduced motion, normal autoplay, offscreen pause, and metadata edit without republishing.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
